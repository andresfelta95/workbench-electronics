#!/usr/bin/env node
/*
 * Regenerates the contrast table in docs/DESIGN-PIXEL-ART.md (§Contrast) from
 * the palette in src/styles/_pixel.scss, so the table cannot drift from the
 * tokens.
 *
 *   node tools/contrast-table.mjs           rewrite the table between the markers
 *   node tools/contrast-table.mjs --check   exit 1 if the table is stale or any
 *                                           pair is below its minimum
 *
 * The colours come from the two palette mixins, `pix-light` and `pix-dark`.
 * Every pair is also checked (not tabulated) with the `prefers-contrast: more`
 * overrides applied on top of each theme. A token may be a hex colour or a
 * var() to another token of the same theme; anything else (color-mix(),
 * rgb(), a named colour) fails loudly instead of being guessed at.
 *
 * PAIRS below is the one place the table's rows are defined. A new colour in
 * _pixel.scss gets its pairs added here, then this script is run.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCSS = join(root, 'src/styles/_pixel.scss');
const SCHEMATIC = join(root, 'src/app/schematic/schematic.ts');
const DOC = join(root, 'docs/DESIGN-PIXEL-ART.md');
const START = '<!-- contrast-table:start';
const END = '<!-- contrast-table:end -->';
const START_LINE = `${START} (generated by tools/contrast-table.mjs; edit the pair list there, not this table) -->`;

// Minimums (WCAG 2.x AA): text 4.5:1; focus rings, component boundaries and
// state indicators 3:1 (1.4.11).
const TEXT = 4.5;
const UI = 3;

// fg/bg: a token name without the `--pix-` prefix, or { token, alpha } for a
// token drawn at an opacity and composited over bg (the dimmed schematic
// stroke; alpha 'dim' is read from schematic.ts).
const PAIRS = [
  ['Control label', 'muted', 'case', TEXT],
  ['Panel text / key text', 'ink', 'case', TEXT],
  ['Key text (raised)', 'ink', 'hi', TEXT],
  ['Pressed key text', 'key-on-ink', 'key-on', TEXT],
  ['Panel heading', 'plate-ink', 'plate', TEXT],
  ['Accented heading run (inverse video)', 'plate', 'plate-ink', TEXT],
  ['LCD value', 'lcd-ink', 'lcd', TEXT],
  ['LCD label / note', 'lcd-muted', 'lcd', TEXT],
  ['Tone accent', 'accent', 'lcd', TEXT],
  ['Tone signal', 'signal', 'lcd', TEXT],
  ['Tone warn', 'warn', 'lcd', TEXT],
  ['Tone danger', 'danger', 'lcd', TEXT],
  ['Schematic ink', 'screen-ink', 'screen', TEXT],
  ['Schematic value', 'screen-muted', 'screen', TEXT],
  ['Schematic highlight / accent label', 'hot', 'screen', TEXT],
  ['Current-flow blocks', 'flow', 'screen', UI],
  [
    'Dimmed stroke (`sch--dim`, ink at {dim} opacity, composited)',
    { token: 'screen-ink', alpha: 'dim' },
    'screen',
    UI,
  ],
  ['Dimmed label (`sch--dim`, switches to muted ink, opaque)', 'screen-muted', 'screen', TEXT],
  ['Fader fill vs empty slot', 'fill', 'lcd', UI],
  ['Outline vs case (field and key edges, fader cap)', 'line', 'case', UI],
  ['Outline vs page', 'line', 'page', UI],
  ['Switch knob, off', 'line', 'lcd', UI],
  ['Switch knob, on', 'key-on-ink', 'key-on', UI],
  ['Focus ring on case', 'focus', 'case', UI],
  ['Focus ring on key / switch face', 'focus', 'hi', UI],
  ['Focus ring on LCD', 'focus', 'lcd', UI],
  ['Focus ring on screen', 'focus', 'screen', UI],
  ['Focus ring on page', 'focus', 'page', UI],
];

function fail(msg) {
  console.error(`contrast-table: ${msg}`);
  process.exit(2);
}

/* ---- Parsing ------------------------------------------------------------ */

const scss = readFileSync(SCSS, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

/** The body of the first `{ … }` block that follows `opener`. */
function block(src, opener, what) {
  const at = src.search(opener);
  if (at < 0) fail(`${what} not found in _pixel.scss`);
  const open = src.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(open + 1, i);
  }
  fail(`unbalanced braces after ${what}`);
}

function declarations(body) {
  const out = {};
  for (const m of body.replace(/\/\/[^\n]*/g, '').matchAll(/--pix-([\w-]+)\s*:\s*([^;]+);/g)) {
    out[m[1]] = m[2].trim();
  }
  return out;
}

const light = declarations(block(scss, /@mixin\s+pix-light\b/, '@mixin pix-light'));
const dark = declarations(block(scss, /@mixin\s+pix-dark\b/, '@mixin pix-dark'));
const more = declarations(
  block(scss, /@media\s*\(\s*prefers-contrast:\s*more\s*\)/, '@media (prefers-contrast: more)'),
);
if (!Object.keys(more).length) fail('no --pix-* overrides under prefers-contrast: more');

const dimMatch = readFileSync(SCHEMATIC, 'utf8').match(
  /\.sch--dim \.stroke,\s*\.sch--dim \.fill\s*\{\s*opacity:\s*([\d.]+)/,
);
if (!dimMatch) fail('could not find the .sch--dim stroke opacity in schematic.ts');
const DIM = Number(dimMatch[1]);

/* ---- Colour maths ------------------------------------------------------- */

function resolve(tokens, name, theme, seen = []) {
  const raw = tokens[name];
  if (raw === undefined) fail(`--pix-${name} is not defined in the ${theme} palette`);
  if (/^#[0-9a-f]{6}$/i.test(raw)) return raw.toLowerCase();
  if (/^#[0-9a-f]{3}$/i.test(raw)) {
    return ('#' + [...raw.slice(1)].map((c) => c + c).join('')).toLowerCase();
  }
  const ref = raw.match(/^var\(\s*--pix-([\w-]+)\s*\)$/);
  if (ref) {
    if (seen.includes(ref[1])) fail(`var() cycle through --pix-${name} (${theme})`);
    return resolve(tokens, ref[1], theme, [...seen, name]);
  }
  fail(`cannot resolve --pix-${name}: ${raw} (${theme}); only #hex and var(--pix-*) are supported`);
}

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const toHex = (c) => '#' + c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');

function luminance(hex) {
  const [r, g, b] = rgb(hex).map((v) => {
    const s = v / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Resolves one pair in one theme to { fg, bg, ratio }. */
function evaluate(tokens, theme, fgSpec, bgName) {
  const bg = resolve(tokens, bgName, theme);
  let fg;
  if (typeof fgSpec === 'string') {
    fg = resolve(tokens, fgSpec, theme);
  } else {
    const alpha = fgSpec.alpha === 'dim' ? DIM : fgSpec.alpha;
    const top = rgb(resolve(tokens, fgSpec.token, theme));
    const under = rgb(bg);
    // Browsers composite in gamma-encoded sRGB; round to the 8-bit result.
    fg = toHex(top.map((v, i) => alpha * v + (1 - alpha) * under[i]));
  }
  return { fg, bg, ratio: ratio(fg, bg) };
}

/* ---- Table -------------------------------------------------------------- */

const label = (text) => text.replace('{dim}', String(DIM));
const fmt = (r) => r.toFixed(2);
const needFmt = (n) => String(n);

const failures = [];
const rows = PAIRS.map(([name, fgSpec, bgName, need]) => {
  const cells = [label(name)];
  for (const [theme, tokens] of [
    ['light', light],
    ['dark', dark],
  ]) {
    const r = evaluate(tokens, theme, fgSpec, bgName);
    if (r.ratio < need) failures.push(`${label(name)} (${theme}): ${fmt(r.ratio)} < ${need}`);
    // Same pair with the prefers-contrast: more overrides on top.
    const m = evaluate({ ...tokens, ...more }, `${theme} + more`, fgSpec, bgName);
    if (m.ratio < need && (m.fg !== r.fg || m.bg !== r.bg)) {
      failures.push(`${label(name)} (${theme}, prefers-contrast: more): ${fmt(m.ratio)} < ${need}`);
    }
    cells.push(`\`${r.fg}\` / \`${r.bg}\``, fmt(r.ratio));
  }
  cells.push(needFmt(need));
  return `| ${cells.join(' | ')} |`;
});

const table = [
  '| Pair | Light fg / bg | Ratio | Dark fg / bg | Ratio | Need |',
  '|---|---|---|---|---|---|',
  ...rows,
].join('\n');

const doc = readFileSync(DOC, 'utf8');
const s = doc.indexOf(START);
const e = doc.indexOf(END);
if (s < 0 || e < s) fail(`markers ${START} … ${END} not found in docs/DESIGN-PIXEL-ART.md`);
const next = doc.slice(0, s) + `${START_LINE}\n\n${table}\n\n` + doc.slice(e);

const check = process.argv.includes('--check');
let stale = false;
if (next !== doc) {
  if (check) {
    stale = true;
    console.error(
      'contrast-table: the table in docs/DESIGN-PIXEL-ART.md is stale. Run `node tools/contrast-table.mjs`.',
    );
  } else {
    writeFileSync(DOC, next);
    console.log('contrast-table: docs/DESIGN-PIXEL-ART.md updated.');
  }
} else if (!check) {
  console.log('contrast-table: docs/DESIGN-PIXEL-ART.md already up to date.');
}

for (const f of failures) console.error(`contrast-table: below minimum: ${f}`);
if (stale || failures.length) process.exit(1);
if (check)
  console.log(
    `contrast-table: ${PAIRS.length} pairs × 2 themes (+ prefers-contrast: more) pass; table is current.`,
  );
